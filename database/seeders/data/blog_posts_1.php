<p>Model bilgisini bulmakta zorlanırsanız, iPad'lerde "Ayarlar &gt; Genel &gt; Hakkında" bölümünden, Android tabletlerde "Ayarlar &gt; Tablet hakkında" bölümünden öğrenebilirsiniz.</p>

<h2>Teslim alma ve gönderim seçenekleri</h2>
<p>Tablet partileri genellikle telefonlara göre daha hacimlidir; özellikle kutulu cihazlarda koli sayısı hızla artar. Bu yüzden teslim şeklini baştan konuşmak önemlidir:</p>
<ul>
<li><strong>Yerinde teslim:</strong> Büyük şehirlerde cihazlar depo, okul veya ofisten teslim alınabilir.</li>
<li><strong>Kargo:</strong> Küçük ve orta ölçekli partiler için uygundur; cihazların darbeye karşı iyi paketlenmesi gerekir.</li>
<li><strong>Nakliye:</strong> Palet halindeki büyük partilerde tercih edilir.</li>
</ul>
<p>Hangi illerde teslim aldığımızı <a href="/bolgeler">bölgeler sayfamızda</a> görebilirsiniz.</p>

<h2>Ne zaman satmalı?</h2>
<p>Tabletler de diğer elektronik ürünler gibi zamanla değer kaybeder. Yeni nesil modeller çıktıkça önceki nesillere olan talep değişir. Kurumsal projesi biten, okul döneminde kullanımdan kalkan ya da depoda beklemeye başlayan tabletleri geciktirmeden değerlendirmek genellikle daha avantajlıdır. Ayrıca uzun süre şarjsız bekleyen cihazlarda pil sağlığı olumsuz etkilenebilir; bu da fiyata yansır.</p>

<h2>iPad ve Android tabletler arasındaki farklar</h2>
<p>Toplu tablet partilerinde iPad'ler ve Android tabletler genellikle birlikte bulunur. İki grubun değerlendirilmesinde bazı farklar vardır:</p>
<ul>
<li><strong>Model tanımlama:</strong> iPad'lerde nesil bilgisi fiyat için çok belirleyicidir; aynı görünen iki iPad farklı nesillerden olabilir. Android tabletlerde ise seri ve model kodu öne çıkar.</li>
<li><strong>Hesap kilidi:</strong> iPad'lerde Apple kimliği, Android tabletlerde Google hesabı ve varsa üretici hesabı kaldırılmalıdır.</li>
<li><strong>Aksesuar uyumu:</strong> Kalem ve klavye gibi aksesuarlar belirli nesillerle uyumludur; listede hangi cihazla birlikte geldiğini belirtmek faydalıdır.</li>
<li><strong>Kullanım alanı:</strong> Giriş seviyesi Android tabletler çoğu zaman eğitim ve kiosk kullanımından gelir; bu cihazlarda kılıf izi ve yoğun kullanım daha sık görülür.</li>
</ul>
<p>Her iki grubu da listede ayrı başlıklar altında yazmak, teklifin daha hızlı ve net hazırlanmasını sağlar.</p>

<h2>Arızalı tabletler de değerlendirilir mi?</h2>
<p>Evet. Ekranı kırık, şarj soketi bozuk, açılmayan ya da dokunmatiği çalışmayan tabletler de toplu satışta değerlendirilir. Bu cihazlar çoğunlukla onarım veya parça değeri üzerinden fiyatlanır. Önemli olan, arızalı cihazları sağlamlardan ayırıp arıza türünü kısaca belirtmektir. "Ekran kırık ama açılıyor" ile "hiç açılmıyor" aynı şekilde değerlendirilmez. Bu ayrım, hem arızalı grubun hem de sağlam cihazların doğru fiyatlanmasını sağlar.</p>

<h2>Toplu tablet satışında veri güvenliği</h2>
<p>Kurumsal ve eğitim amaçlı tabletlerde öğrenci, müşteri ya da çalışan verileri bulunabilir. Bu nedenle cihazları teslim etmeden önce yalnızca uygulamaları kaldırmak yeterli değildir; cihazın tamamen sıfırlanması gerekir. Fabrika ayarlarına dönüş, cihazdaki verileri kullanıcı erişimine kapatır. Hassas veri barındıran kurumlar için cihaz listesi üzerinde hangi cihazın sıfırlandığını işaretlemek ve bu listeyi saklamak, iç denetim açısından da faydalıdır.</p>
<p>Sıfırlama sonrası cihazı kısa bir süre açık bırakıp kurulum ekranına geldiğini görmek, işlemin tamamlandığını doğrulamanın en kolay yoludur. Kurulum ekranında bir hesap isteniyorsa hesap kilidi hâlâ duruyor demektir. Bu kontrolü partideki her cihaz için tekrarlamak zaman alsa da teslimde yaşanabilecek geri dönüşleri ve ek görüşmeleri önler; sonuçta satış süreci daha hızlı tamamlanır.</p>

