<p>Zamanlamanın bir diğer boyutu da cihazların bekleme koşullarıdır. Uzun süre kullanılmadan duran telefonlarda piller tamamen boşalabilir; bu da hem pil sağlığını olumsuz etkiler hem de teslim sırasında cihazın açılmaması gibi durumlara yol açar. Uzun süre bekleyecek cihazları belirli aralıklarla kısmen şarj etmek faydalıdır.</p>

<h2>Homojen ve karışık parti farkı</h2>
