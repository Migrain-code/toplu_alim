<p>Tabletler, telefonlara göre daha çok kurumsal ve toplu kullanım alanına sahiptir. Bu yüzden elde toplu tablet birikmesi de oldukça yaygındır:</p>
<ul>
<li><strong>Eğitim kurumları:</strong> Dijital eğitim projelerinde kullanılan ve yenilenen tabletler.</li>
<li><strong>Şirketler:</strong> Saha ekipleri, satış temsilcileri veya depo personeli için alınmış cihazlar.</li>
<li><strong>Restoran ve perakende:</strong> Sipariş, kasa ya da menü ekranı olarak kullanılan tabletler.</li>
<li><strong>Bayi ve distribütörler:</strong> Stok fazlası, sezon sonu kalan veya teşhirde kullanılmış ürünler.</li>
<li><strong>E-ticaret satıcıları:</strong> Müşteri iadesi ve kutusu açılmış ürünler.</li>
</ul>

<h2>Tabletleri satabileceğiniz kanallar</h2>

<h3>Toplu elektronik alımı yapan firmalar</h3>
<p>Karışık bir tablet partisini tek seferde değerlendirmek için en uygun kanaldır. Sıfır, ikinci el ve arızalı tabletler aynı görüşmede fiyatlandırılabilir. <a href="/toplu-tablet-alimi">Toplu tablet alımı</a> sayfamızda hangi tablet türlerini aldığımızı ayrıntılı olarak görebilirsiniz.</p>

<h3>Yenileme atölyeleri</h3>
<p>Belirli modelleri onarıp yeniden satan atölyeler seçici davranabilir; genellikle partinin tamamı yerine işlerine yarayan modelleri tercih ederler.</p>

<h3>Tekli satış kanalları</h3>
<p>İlan siteleri tek tek satış için kullanılabilir; ancak onlarca tablet için ilan, pazarlık, kargo ve iade süreci ciddi bir iş yükü oluşturur.</p>

<h2>Tablette fiyatı belirleyen bilgiler</h2>
<p>Tabletlerde fiyatı belirleyen başlıklar telefonlara benzer, ancak birkaç farkla:</p>
<ol>
<li><strong>Marka ve model:</strong> iPad, Galaxy Tab, Lenovo Tab gibi seriler ve nesil bilgisi.</li>
<li><strong>Ekran boyutu:</strong> Aynı serinin farklı ekran boyutlu sürümleri farklı fiyatlanır.</li>
<li><strong>Kapasite:</strong> Depolama alanı fiyatı doğrudan etkiler.</li>
<li><strong>Bağlantı tipi:</strong> Yalnız Wi-Fi ya da hücresel (SIM kartlı) sürüm bilgisi.</li>
<li><strong>Durum:</strong> Sıfır, teşhir, ikinci el temiz, kusurlu veya arızalı.</li>
<li><strong>Pil durumu:</strong> Uzun süre şarjda bekleyen kurumsal tabletlerde pil yıpranması sık görülür.</li>
<li><strong>Aksesuar:</strong> Orijinal şarj adaptörü, kalem, klavyeli kılıf gibi aksesuarlar.</li>
<li><strong>Hesap kilidi:</strong> iCloud veya Google hesabının kaldırılıp kaldırılmadığı.</li>
</ol>

<h2>Kurumsal tabletlerde özel durumlar</h2>
<p>Eğitim kurumları ve şirketlerden gelen tablet partilerinde bazı ek konular öne çıkar:</p>
<ul>
<li><strong>Cihaz yönetimi (MDM):</strong> Kurumsal tabletler çoğunlukla bir yönetim sistemine kayıtlıdır. Satıştan önce bu kaydın kaldırılması gerekir; aksi halde cihaz yeni kullanıcıya kurulamaz.</li>
<li><strong>Kiosk modu ve kısıtlamalar:</strong> Menü ekranı veya kasa olarak kullanılan tabletlerde özel ayarlar bulunabilir; sıfırlama ile kaldırılmalıdır.</li>
<li><strong>Kılıf ve sabitleme aparatları:</strong> Duvara ya da tezgâha sabitlenmiş tabletlerde montaj izleri olabilir; bu, durum bilgisine eklenmelidir.</li>
<li><strong>Etiket ve envanter numaraları:</strong> Kurumsal etiketler cihazın kozmetik değerlendirmesinde dikkate alınır; çıkarılabiliyorsa çıkarmak faydalıdır.</li>
</ul>

<h2>Teslim öncesi hazırlık adımları</h2>
<ol>
<li>Cihazlardaki verilerin yedeğini alın.</li>
<li>iPad'lerde Apple kimliğinden çıkış yapıp "Ayarlar &gt; Genel &gt; Aktar veya Sıfırla &gt; Tüm İçeriği ve Ayarları Sil" yolunu izleyin.</li>
<li>Android tabletlerde önce Google hesabını kaldırın, ardından fabrika ayarlarına dönün.</li>
<li>MDM kaydı varsa yönetim panelinden cihazları silin.</li>
<li>SIM kartlı modellerde SIM kartları çıkarın.</li>
<li>Cihazları duruma göre gruplayıp etiketleyin.</li>
</ol>

<h2>Partiyi gruplama önerisi</h2>
<p>Tablet partisini aşağıdaki gibi gruplamak, her grubun kendi değerinden fiyatlanmasını sağlar:</p>
<ul>
<li><strong>Sıfır ve stok fazlası:</strong> Hiç açılmamış kutular; ayrıntılar için <a href="/stok-fazlasi-elektronik-alimi">stok fazlası elektronik alımı</a>.</li>
<li><strong>Teşhir ve iade:</strong> Kutusu açılmış, az kullanılmış cihazlar; bkz. <a href="/teshir-iade-elektronik-alimi">teşhir ve iade ürün alımı</a>.</li>
<li><strong>İkinci el çalışır:</strong> Kozmetik durumuna göre temiz ve kusurlu olarak alt gruplara ayrılabilir.</li>
<li><strong>Arızalı:</strong> Ekranı kırık, şarj almayan, açılmayan tabletler ayrı yazılmalıdır.</li>
</ul>

<h2>Tabletleri toptan satarken sık yapılan hatalar</h2>
<ul>
<li>Wi-Fi ve hücresel sürümleri aynı satırda yazmak.</li>
<li>Ekran boyutu ve nesil bilgisini atlamak.</li>
<li>Yönetim sistemi kaydını silmeden teslim etmek.</li>
<li>Aksesuarları cihazlardan ayrı bir kutuda unutmak ya da eksik bildirmek.</li>
<li>Uzun süre kullanılmamış cihazları şarj etmeden göndermek; açılmayan cihaz arızalı sanılabilir.</li>
</ul>

<h2>Tablet partisi için örnek liste</h2>
<p>Teklif sürecini hızlandırmak için listenizi aşağıdaki başlıklarla hazırlayabilirsiniz. Basit bir tablo yeterlidir:</p>
<ul>
<li><strong>Marka ve seri:</strong> Örneğin "iPad", "Galaxy Tab", "Lenovo Tab".</li>
<li><strong>Nesil veya model kodu:</strong> Cihazın arkasında ya da ayarlar menüsünde yazan model bilgisi.</li>
<li><strong>Ekran boyutu ve kapasite.</strong></li>
<li><strong>Bağlantı tipi:</strong> Wi-Fi veya Wi-Fi + hücresel.</li>
<li><strong>Adet.</strong></li>
<li><strong>Durum grubu:</strong> Sıfır, teşhir, ikinci el temiz, ikinci el kusurlu, arızalı.</li>
