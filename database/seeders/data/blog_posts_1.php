<li><strong>Homojen parti:</strong> Aynı model ve benzer durumdaki çok sayıda cihaz. Örneğin bir şirketin aynı anda yenilediği kurumsal telefonlar. Bu tür partilerde model başına birim fiyat vermek kolaydır ve kontrol hızlı ilerler.</li>
